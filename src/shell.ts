import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { configDir } from "./config.js";
import { run } from "./util.js";

export type HookShell = "bash" | "zsh";
export const isHookShell = (s: string): s is HookShell => s === "bash" || s === "zsh";

const START = "# >>> whatcmd >>>";
const END = "# <<< whatcmd <<<";

/**
 * Bash: Enter is rebound to run our hook first. If the line starts with the prefix, the hook
 * replaces it with the generated command and swallows that Enter, so nothing runs until
 * the user presses Enter again. The raw line never reaches the shell parser, so
 * apostrophes, ">" and "*" in the request are safe.
 */
export function bashHook(prefix: string): string {
  return `# whatcmd shell hook for bash — generated by \`whatcmd shell bash\`
[[ $- == *i* ]] || return 0
__whatcmd_prefix='${prefix}'
__whatcmd_hook() {
  local st=$? line=$READLINE_LINE ask out last
  local -a extra=()
  if [[ $line == "$__whatcmd_prefix+ "* ]]; then
    ask=\${line#"$__whatcmd_prefix+ "}
    extra=(--refine)
  elif [[ $line == "$__whatcmd_prefix "* ]]; then
    ask=\${line#"$__whatcmd_prefix "}
  else
    bind '"\\C-x\\C-j": accept-line'
    return
  fi
  # The last command run in this shell and its exit status (used by /w+ "fix that").
  last=$(HISTTIMEFORMAT= builtin history 1); last=\${last#*[0-9]  }
  extra+=("--last-status=$st" "--last-cmd=$last")
  if ! command -v whatcmd >/dev/null 2>&1; then
    printf 'whatcmd: not found on PATH\\n' >&2
  else
    out=$(command whatcmd --raw "--session=$$" "\${extra[@]}" -- "$ask")
    if [[ -n $out ]]; then
      READLINE_LINE=$out
      READLINE_POINT=\${#READLINE_LINE}
    fi
  fi
  bind '"\\C-x\\C-j": ""'
}
for __whatcmd_map in emacs vi-insert; do
  bind -m "$__whatcmd_map" -x '"\\C-x\\C-k": __whatcmd_hook'
  bind -m "$__whatcmd_map" '"\\C-m": "\\C-x\\C-k\\C-x\\C-j"'
done
unset __whatcmd_map
`;
}

/** Zsh: wrap the accept-line widget. Messages are shown with `zle -M` under the prompt. */
export function zshHook(prefix: string): string {
  return `# whatcmd shell hook for zsh — generated by \`whatcmd shell zsh\`
[[ -o interactive ]] || return 0
typeset -g __whatcmd_prefix='${prefix}'
__whatcmd_accept_line() {
  local st=$? ask out msg
  local -a extra
  if [[ $BUFFER == "$__whatcmd_prefix+ "* ]]; then
    ask=\${BUFFER#"$__whatcmd_prefix+ "}
    extra=(--refine)
  elif [[ $BUFFER == "$__whatcmd_prefix "* ]]; then
    ask=\${BUFFER#"$__whatcmd_prefix "}
  else
    zle .accept-line
    return
  fi
  # The last command run in this shell and its exit status (used by /w+ "fix that").
  extra+=("--last-status=$st" "--last-cmd=$(fc -ln -1 2>/dev/null)")
  if (( ! $+commands[whatcmd] )); then
    zle -M "whatcmd: not found on PATH"
    return 0
  fi
  local errf="\${TMPDIR:-/tmp}/whatcmd.$$.err"
  out=$(command whatcmd --raw "--session=$$" "\${extra[@]}" -- "$ask" 2>"$errf")
  msg=$(<"$errf"); rm -f "$errf"
  if [[ -n $out ]]; then
    BUFFER=$out
    CURSOR=\${#BUFFER}
  fi
  zle redisplay
  [[ -n $msg ]] && zle -M "$msg"
  return 0
}
zle -N accept-line __whatcmd_accept_line
`;
}

export function hookScript(shell: HookShell, prefix: string): string {
  return shell === "bash" ? bashHook(prefix) : zshHook(prefix);
}

export function hookFile(shell: HookShell): string {
  return path.join(configDir(), `hook.${shell}`);
}

export function rcFile(shell: HookShell, osName: string): string {
  const home = os.homedir();
  if (shell === "zsh") return path.join(process.env.ZDOTDIR || home, ".zshrc");
  // macOS Terminal opens login shells, which read .bash_profile rather than .bashrc
  return path.join(home, osName === "macos" ? ".bash_profile" : ".bashrc");
}

export function isHookInstalled(shell: HookShell, osName: string): boolean {
  try {
    return fs.readFileSync(rcFile(shell, osName), "utf8").includes(START);
  } catch {
    return false;
  }
}

/** (Re)write the hook file for each shell that has it installed. Used when the prefix changes. */
export function refreshHookFiles(prefix: string): void {
  for (const shell of ["bash", "zsh"] as const) {
    if (fs.existsSync(hookFile(shell))) fs.writeFileSync(hookFile(shell), hookScript(shell, prefix));
  }
}

export function installHook(shell: HookShell, prefix: string, osName: string): { rc: string; hook: string; added: boolean } {
  const hook = hookFile(shell);
  fs.mkdirSync(path.dirname(hook), { recursive: true });
  fs.writeFileSync(hook, hookScript(shell, prefix));
  const rc = rcFile(shell, osName);
  if (isHookInstalled(shell, osName)) return { rc, hook, added: false };
  const home = os.homedir();
  const shown = hook.startsWith(home + path.sep) ? `$HOME${hook.slice(home.length)}` : hook;
  const block = `\n${START}\n[ -f "${shown}" ] && . "${shown}"\n${END}\n`;
  fs.appendFileSync(rc, block);
  return { rc, hook, added: true };
}

export function uninstallHook(shell: HookShell, osName: string): boolean {
  const rc = rcFile(shell, osName);
  let text: string;
  try {
    text = fs.readFileSync(rc, "utf8");
  } catch {
    return false;
  }
  const re = new RegExp(`\\n?${START}[\\s\\S]*?${END}\\n?`, "g");
  if (!re.test(text)) return false;
  fs.writeFileSync(rc, text.replace(re, "\n"));
  try {
    fs.unlinkSync(hookFile(shell));
  } catch {}
  return true;
}

/** The bash shortcut needs bash 4+ (READLINE_LINE). macOS ships bash 3.2. */
export function bashTooOld(bashPath = process.env.SHELL && /bash$/.test(process.env.SHELL) ? process.env.SHELL : "bash"): boolean {
  const r = run(bashPath, ["-c", "echo ${BASH_VERSINFO[0]}"], { timeoutMs: 2000 });
  const major = Number(r.stdout.trim());
  return r.ok && Number.isFinite(major) && major < 4;
}
